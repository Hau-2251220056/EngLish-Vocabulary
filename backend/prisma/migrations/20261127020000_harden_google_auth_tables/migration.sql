BEGIN;

ALTER TABLE public."AUTH_IDENTITY" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."GOOGLE_AUTH_CHALLENGE" ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public."AUTH_IDENTITY", public."GOOGLE_AUTH_CHALLENGE" FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL PRIVILEGES ON TABLE public."AUTH_IDENTITY", public."GOOGLE_AUTH_CHALLENGE" FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL PRIVILEGES ON TABLE public."AUTH_IDENTITY", public."GOOGLE_AUTH_CHALLENGE" FROM authenticated;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        REVOKE ALL PRIVILEGES ON TABLE public."AUTH_IDENTITY", public."GOOGLE_AUTH_CHALLENGE" FROM service_role;
    END IF;
END $$;

COMMIT;

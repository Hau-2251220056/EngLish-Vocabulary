export const DAILY_GOAL_PHASE_B_FAILURE_CODES = Object.freeze({
  CONFIG_REJECTED: "CONFIG_REJECTED",
  PRISMA_LOAD_FAILED: "PRISMA_LOAD_FAILED",
  TRANSACTION_ACQUIRE_FAILED: "TRANSACTION_ACQUIRE_FAILED",
  READ_ONLY_ENFORCEMENT_FAILED: "READ_ONLY_ENFORCEMENT_FAILED",
  TARGET_OBSERVATION_FAILED: "TARGET_OBSERVATION_FAILED",
  TARGET_VERIFICATION_FAILED: "TARGET_VERIFICATION_FAILED",
  INTERNAL_EVIDENCE_INVALID: "INTERNAL_EVIDENCE_INVALID",
  CONNECTED_EVIDENCE_INVALID: "CONNECTED_EVIDENCE_INVALID",
  TARGET_FIELD_INVALID: "TARGET_FIELD_INVALID",
  DATABASE_NAME_MISMATCH: "DATABASE_NAME_MISMATCH",
  SCHEMA_NAME_MISMATCH: "SCHEMA_NAME_MISMATCH",
  OWNERSHIP_MARKER_MISMATCH: "OWNERSHIP_MARKER_MISMATCH",
  TARGET_IDENTITY_MISMATCH: "TARGET_IDENTITY_MISMATCH",
  AUTHORIZATION_CONTINUITY_FAILED: "AUTHORIZATION_CONTINUITY_FAILED",
  ENDPOINT_DIAGNOSTIC_INVALID: "ENDPOINT_DIAGNOSTIC_INVALID",
  PORT_DIAGNOSTIC_INVALID: "PORT_DIAGNOSTIC_INVALID",
  HISTORY_READ_FAILED: "HISTORY_READ_FAILED",
  OBSERVER_CLEANUP_FAILED: "OBSERVER_CLEANUP_FAILED",
  ROLLBACK_FAILED: "ROLLBACK_FAILED",
  DISCONNECT_FAILED: "DISCONNECT_FAILED",
  UNKNOWN_PHASE_B_FAILURE: "UNKNOWN_PHASE_B_FAILURE",
});

const ALLOWED_CODES = new Set(Object.values(DAILY_GOAL_PHASE_B_FAILURE_CODES));
const TARGET_PREDICATE_CODES = new Set([
  DAILY_GOAL_PHASE_B_FAILURE_CODES.INTERNAL_EVIDENCE_INVALID,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.CONNECTED_EVIDENCE_INVALID,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.TARGET_FIELD_INVALID,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.DATABASE_NAME_MISMATCH,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.SCHEMA_NAME_MISMATCH,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.OWNERSHIP_MARKER_MISMATCH,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.TARGET_IDENTITY_MISMATCH,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.AUTHORIZATION_CONTINUITY_FAILED,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.ENDPOINT_DIAGNOSTIC_INVALID,
  DAILY_GOAL_PHASE_B_FAILURE_CODES.PORT_DIAGNOSTIC_INVALID,
]);
const TRUSTED_FAILURE_CODES = new WeakMap();

export function createDailyGoalPhaseBFailure(
  failureCode,
  {
    errorCode = "DAILY_GOAL_PHASE_B_FAILED",
    message = "Daily Goal Phase B observation failed.",
  } = {},
) {
  const safeCode = ALLOWED_CODES.has(failureCode)
    ? failureCode
    : DAILY_GOAL_PHASE_B_FAILURE_CODES.UNKNOWN_PHASE_B_FAILURE;
  const error = new Error(message);
  error.code = errorCode;
  TRUSTED_FAILURE_CODES.set(error, safeCode);
  return error;
}

export function getDailyGoalPhaseBFailureCode(error) {
  return TRUSTED_FAILURE_CODES.get(error)
    ?? DAILY_GOAL_PHASE_B_FAILURE_CODES.UNKNOWN_PHASE_B_FAILURE;
}

export function getDailyGoalTargetPredicateFailureCode(error) {
  const failureCode = TRUSTED_FAILURE_CODES.get(error);
  return TARGET_PREDICATE_CODES.has(failureCode)
    ? failureCode
    : DAILY_GOAL_PHASE_B_FAILURE_CODES.TARGET_VERIFICATION_FAILED;
}

export function normalizeDailyGoalPhaseBFailure(error, fallbackCode) {
  if (TRUSTED_FAILURE_CODES.has(error)) return error;
  return createDailyGoalPhaseBFailure(fallbackCode);
}
